import re
import unittest
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class DesktopContract(unittest.TestCase):
    """The built Desktop file is generated from the source and carries the fixes."""

    def test_source_and_build_contract(self):
        src = (ROOT / "desktop" / "src" / "plugin.src.js").read_text()
        built = (ROOT / "desktop" / "plugin.js").read_text()
        self.assertTrue(built.startswith("// GENERATED by desktop/build.py"))
        self.assertIn("/card?id=", src)
        self.assertIn("/outside/text?id=", src)
        self.assertIn("outsideText?.__version === item.version", src)
        self.assertIn("/card/ask", src)
        # When the answer says "keep blocked", the shortcut keeps it blocked and the ⏎ mark says so.
        self.assertIn("keycap: saysKeep ? '⏎' : undefined", src)
        self.assertIn("keycap: saysKeep ? undefined : '⏎'", src)
        self.assertNotIn("keycap: '⏎', disabled: busy, onClick: release", src)
        self.assertIn("askEnabled: q.ask_enabled !== false", src)
        self.assertIn("item.id))", src)
        self.assertNotIn("${item.id}:${item.version}", src)
        self.assertIn("!(q.errors || []).length", src)
        self.assertIn("r && r.released", src)
        self.assertIn("kept blocked", src)
        self.assertIn("Use as answer", src)
        self.assertIn("Discuss in chat", src)
        self.assertIn("host.composer.setDraft", src)
        self.assertIn("TL;DR", src)
        self.assertIn("askSend(false, TLDR_ASK)", src)   # one click asks; no typing
        # An answered card that is still blocked offers a release, not a second answer.
        self.assertIn("item.tier === 'answered'", src)
        self.assertIn("Release (unbl0ck)", src)
        # Undo for "Not for me" must call the backend route that exists.
        self.assertIn("'/unhide'", src)
        api = (ROOT / "dashboard" / "plugin_api.py").read_text()
        self.assertIn('@router.post("/unhide")', api)
        # A kept-blocked answer must not stamp the card UNBL0CKED.
        self.assertIn("'■ ANSWERED'", src)
        self.assertIn("'■ ANSWERED'", built)

    def test_chip_renders_the_ask_count_from_queue_data(self):
        src = (ROOT / "desktop" / "src" / "plugin.src.js").read_text()
        script = r'''const fs = require('fs');
const src = fs.readFileSync(process.argv[1], 'utf8');
const helper = src.match(/function askCount\(q\) \{[^\n]*\}/)?.[0] || 'function askCount(q) { return q.count; }';
const chip = src.match(/function Chip\(\) \{[\s\S]*?\n\}/)?.[0];
if (!helper || !chip) throw new Error('count renderer or helper missing');
const jsx = (_type, props) => props;
const render = new Function('jsx', 'useValue', '$queue', `${helper}; return (${chip});`)(
  jsx, () => ({count: 10, counts: {asks: 1}}), Symbol('queue'));
const result = render();
if (result.children !== '◆ 1 NEEDS YOU') throw new Error(`unexpected chip: ${result.children}`);
'''
        subprocess.run(["node", "-e", script, str(ROOT / "desktop" / "src" / "plugin.src.js")],
                       check=True, capture_output=True, text=True)

    def test_outside_cards_render_safe_text_and_send_done_to_the_backend(self):
        script = r'''
const fs = require('fs');
const src = fs.readFileSync(process.argv[1], 'utf8');
const views = src.slice(src.indexOf('function Item('), src.indexOf('function Chip('));
const node = (type, props) => ({type, props});
const noop = () => {};
const env = {
  jsx: node, jsxs: node, useState: x => [x, noop], useEffect: noop, useRef: () => ({}),
  platformLabel: x => x, LOCAL_PLATFORMS: [], KEEP_BLOCKED: /keep blocked/i,
  button: props => node('button', props), openBoard: noop, ago: () => '', ageClass: () => '', pad: String,
  sfx: {play: noop}, petEmit: noop, host: {notifyError: e => {throw e}},
  $undo: {set: noop}, $queue: 'queue', $fxOn: 'fx', UNDO_MS: 12000, askCount: q => q.count,
  Field: noop, Watermark: noop, Banner: noop, Pet: noop, Ticker: noop, FxToggle: noop, SfxToggle: noop,
  grainUrl: () => '', oldestAskSince: items => items.reduce((m, x) => Math.min(m, x.since ?? Infinity), Infinity),
};
const {Item, Page} = new Function('env', `with(env) { ${views}; return {Item, Page}; }`)(env);
function all(n) {
  if (n == null) return [];
  if (Array.isArray(n)) return n.flatMap(all);
  if (typeof n !== 'object') return [n];
  return [n, ...all(n.props?.children)];
}
function text(n) { return all(n).filter(x => typeof x === 'string').join(''); }
const requests = [];
const ctx = {rest: async (url, options) => {requests.push({url, ...options}); return {ok: true}}};
const refresh = async () => {};
const base = {id: 'outside:filed:1', version: 'v1', source: 'outside', kind: 'draft', origin: 'filed',
  title: '<img onerror=bad()>', ask: 'Full original text', bluf: 'Send the reply', act_where: 'Outlook → Drafts',
  ref: 'javascript:alert(1)', since: 1};
(async () => {
  const filed = Item({ctx, item: base, n: 1, refresh, askEnabled: false});
  for (const required of ['DRAFT · FILED BY AGENT', base.title, base.bluf, '+ FULL TEXT', 'Act in: Outlook → Drafts', base.ref]) {
    if (!text(filed).includes(required)) throw new Error(`missing filed card content: ${required}`);
  }
  if (all(filed).some(x => x?.type === 'a' || x?.props?.dangerouslySetInnerHTML || x?.props?.href)) throw new Error('reference must stay text');
  const buttons = all(filed).filter(x => x?.type === 'button');
  if (!buttons.some(x => text(x) === 'Not for me')) throw new Error('missing hide');
  const done = buttons.find(x => text(x) === 'Done');
  if (!done || done.props.kind !== 'primary') throw new Error('missing primary Done');
  await done.props.onClick();
  if (requests[0]?.url !== '/outside/done' || requests[0].body.id !== base.id || requests[0].body.version !== 'v1') throw new Error('Done request lost identity/version');
  const folder = Item({ctx, item: {...base, kind: 'notes', origin: 'folder'}, n: 1, refresh, askEnabled: false});
  if (!text(folder).includes('NOTES · FOLDER') || !text(folder).includes('Done — hides until the file changes')) throw new Error('folder Done must describe hiding');
  const q = {items: [base, {source: 'kanban', tier: 'normal', id: 'k'}, {source: 'chat', id: 'c'}], count: 3, errors: [], at: Date.now()};
  env.useValue = key => key === 'queue' ? q : false;
  const page = text(Page({ctx, refresh}));
  if (!(page.indexOf('KANBAN.CARDS') < page.indexOf('OUTSIDE.HERMES') && page.indexOf('OUTSIDE.HERMES') < page.lastIndexOf('CHATS'))) throw new Error('outside group is missing or out of order');
})().catch(e => { console.error(e); process.exitCode = 1 });
'''
        for path in (ROOT / "desktop/src/plugin.src.js", ROOT / "desktop/plugin.js"):
            with self.subTest(path=path.name):
                result = subprocess.run(["node", "-e", script, str(path)], capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)

    def test_oldest_age_ignores_stuck_and_answered_cards(self):
        script = r'''const fs = require('fs');
const src = fs.readFileSync(process.argv[1], 'utf8');
const helper = src.match(/function oldestAskSince\(items\) \{[\s\S]*?\n\}/)?.[0];
if (!helper) throw new Error('oldest ask helper missing');
const oldestAskSince = new Function(`${helper}; return oldestAskSince;`)();
const since = oldestAskSince([
  {tier: 'stuck', since: 1},
  {tier: 'answered', since: 2},
  {tier: 'ask', since: 30},
  {tier: 'ask', since: 40}
]);
if (since !== 30) throw new Error(`oldest ask timestamp was ${since}`);
'''
        subprocess.run(["node", "-e", script, str(ROOT / "desktop" / "src" / "plugin.src.js")],
                       check=True, capture_output=True, text=True)

    def test_every_answer_post_sends_the_card_version(self):
        # A stricter static check than the substrings above (not a render test; see F20 notes): each
        # /kanban/answer call's body, in the source and the built file, must carry `version`.
        for name in ("src/plugin.src.js", "plugin.js"):
            text = (ROOT / "desktop" / name).read_text()
            calls = re.findall(r"ctx\.rest\('/kanban/answer',\s*\{(.*?)\n\s*\}\)", text, re.S)
            self.assertGreaterEqual(len(calls), 2, name)   # answer and release
            for body in calls:
                self.assertRegex(body, r"body:\s*\{[^}]*\bversion:\s*item\.version\b", name)


if __name__ == "__main__":
    unittest.main()
