import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class DesktopContract(unittest.TestCase):
    """The built Desktop file is generated from the source and carries the fixes."""

    def test_source_and_build_contract(self):
        src = (ROOT / "desktop" / "src" / "plugin.src.js").read_text()
        built = (ROOT / "desktop" / "plugin.js").read_text()
        self.assertTrue(built.startswith("// GENERATED by desktop/build.py"))
        self.assertIn("/card?id=", src)
        self.assertIn("/card/ask", src)
        self.assertIn("askEnabled: q.ask_enabled !== false", src)
        self.assertIn("item.id))", src)
        self.assertNotIn("${item.id}:${item.version}", src)
        self.assertIn("!(q.errors || []).length", src)
        self.assertIn("r && r.released", src)
        self.assertIn("kept blocked", src)
        self.assertIn("Use as answer", src)
        self.assertIn("Discuss in chat", src)
        self.assertIn("host.composer.setDraft", src)
        self.assertIn("Ask about this card", src)


if __name__ == "__main__":
    unittest.main()
