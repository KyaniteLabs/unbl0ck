#!/usr/bin/env python3
"""Build desktop/plugin.js from desktop/src/plugin.src.js by inlining the subset fonts.

The Desktop loads one plain ESM file, so the woff2 fonts ride inside it as base64.
Fonts: Rajdhani and Share Tech Mono (SIL OFL 1.1), Latin subset via pyftsubset.
"""
import base64, json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
FONTS = {
    "Rajdhani:500": "Rajdhani-Medium.woff2",
    "Rajdhani:700": "Rajdhani-Bold.woff2",
    "ShareTechMono:400": "ShareTechMono-Regular.woff2",
}
src = (HERE / "src" / "plugin.src.js").read_text()
blob = {k: base64.b64encode((HERE / "fonts" / f).read_bytes()).decode() for k, f in FONTS.items()}
marker = "/*@@FONTS@@*/ {}"
assert src.count(marker) == 1, "font marker missing"
out = "// GENERATED by desktop/build.py from desktop/src/plugin.src.js. Do not edit.\n" + src.replace(marker, json.dumps(blob))
(HERE / "plugin.js").write_text(out)
print(f"plugin.js {len(out)//1024} KB")

# Canon kit: the Desktop CSS is the visual reference for every surface (design/CANON.md).
# Emit it as plain CSS with the font faces pointing at design/fonts/, so gadgets read one file.
start = src.index("const CSS = `") + len("const CSS = `")
css = src[start:src.index("\n`\n", start)]
css = css[css.index(".ub{"):]
faces = "\n".join(
    f"@font-face{{font-family:'UB {k.split(':')[0]}';font-weight:{k.split(':')[1]};src:url(fonts/{f}) format('woff2')}}"
    for k, f in FONTS.items())
canon = HERE.parent / "design"
(canon / "fonts").mkdir(exist_ok=True)
for f in FONTS.values():
    (canon / "fonts" / f).write_bytes((HERE / "fonts" / f).read_bytes())
(canon / "unbl0ck.css").write_text("/* GENERATED by desktop/build.py from desktop/src/plugin.src.js. Do not edit. */\n" + faces + "\n" + css + "\n")
print("design/unbl0ck.css written")
